package com.google.android.maps.testing.golden

import android.graphics.Bitmap
import android.util.LruCache
import com.google.android.gms.maps.model.Tile
import com.google.android.gms.maps.model.TileProvider
import java.io.ByteArrayOutputStream

// [START maps_golden_tile_provider]
/**
 * A [TileProvider] that serves deterministic synthetic raster tiles for Google Maps SDK screenshot
 * and golden image testing.
 *
 * Replaces remote network-fetched map tiles with locally computed bitmaps generated by
 * [GoldenTileStrategy]. Built-in LRU caching avoids re-rasterization and PNG re-compression during
 * map panning, zooming, and camera transitions.
 *
 * @param strategy The [GoldenTileStrategy] to use for tile generation. Defaults to [GoldenTileStrategy.CoordinateGrid].
 * @param tileSize Dimension in pixels for tile width and height. Standard Web Mercator is 256.
 * @param cacheSize Maximum number of compressed tile byte arrays to retain in memory. Defaults to 128.
 */
public class GoldenTileProvider(
  public val strategy: GoldenTileStrategy = GoldenTileStrategy.CoordinateGrid(),
  public val tileSize: Int = 256,
  cacheSize: Int = 128,
) : TileProvider {

  private val tileCache = LruCache<Long, ByteArray>(cacheSize)

  override fun getTile(x: Int, y: Int, zoom: Int): Tile {
    if (zoom < 0 || zoom > 22 || x < 0 || y < 0) {
      return TileProvider.NO_TILE
    }
    val key = computeKey(x, y, zoom)
    val cached = tileCache.get(key)
    if (cached != null) {
      return Tile(tileSize, tileSize, cached)
    }

    val bitmap = strategy.generateTile(x, y, zoom, tileSize)
    val stream = ByteArrayOutputStream()
    try {
      bitmap.compress(Bitmap.CompressFormat.PNG, 100, stream)
      val bytes = stream.toByteArray()
      tileCache.put(key, bytes)
      return Tile(tileSize, tileSize, bytes)
    } finally {
      bitmap.recycle()
    }
  }

  /**
   * Clears all in-memory cached tile byte arrays.
   */
  public fun clearCache() {
    tileCache.evictAll()
  }

  /**
   * Returns the number of tiles currently cached in memory.
   */
  public fun cachedTileCount(): Int = tileCache.size()

  private companion object {
    /**
     * Packs (zoom, x, y) into a 64-bit Long key.
     * zoom: bits 48..55 (8 bits, 0..255)
     * x:    bits 24..47 (24 bits, 0..16,777,215)
     * y:    bits 0..23  (24 bits, 0..16,777,215)
     */
    private fun computeKey(x: Int, y: Int, zoom: Int): Long {
      val zPart = (zoom.toLong() and 0xFF) shl 48
      val xPart = (x.toLong() and 0xFFFFFF) shl 24
      val yPart = y.toLong() and 0xFFFFFF
      return zPart or xPart or yPart
    }
  }
}
// [END maps_golden_tile_provider]
